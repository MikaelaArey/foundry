// Writes prisma/postgres/schema.prisma: the same data model as
// prisma/schema.prisma, but for a hosted Postgres database. Local development
// keeps using SQLite; production builds use this generated copy.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const source = fs.readFileSync(path.join(root, "prisma", "schema.prisma"), "utf8");
let pg = source.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
if (pg === source) throw new Error('Expected provider = "sqlite" in prisma/schema.prisma');

// Hosted databases often give a pooled address (DATABASE_URL) and a direct one.
// Setting up tables needs the direct one, so use it when it's available.
const direct = ["DIRECT_URL", "DATABASE_URL_UNPOOLED", "POSTGRES_URL_NON_POOLING"].find((name) => process.env[name]);
if (direct) {
  pg = pg.replace(/(url\s*=\s*env\("DATABASE_URL"\))/, `$1\n  directUrl = env("${direct}")`);
  console.log(`Using ${direct} for setting up tables`);
}

const header = "// GENERATED by scripts/use-postgres.mjs from prisma/schema.prisma. Edit that file instead.\n";
fs.mkdirSync(path.join(root, "prisma", "postgres"), { recursive: true });
fs.writeFileSync(path.join(root, "prisma", "postgres", "schema.prisma"), header + pg);
console.log("Wrote prisma/postgres/schema.prisma");
