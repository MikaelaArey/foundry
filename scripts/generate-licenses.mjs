// Writes THIRD_PARTY_LICENSES.md from the installed production dependencies.
// Run with `npm run licenses` after installing or updating packages.
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const LICENSE_FILES = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

const lines = execSync("npm ls --omit=dev --all --parseable --long", { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] })
  .split("\n")
  .filter(Boolean)
  .slice(1); // first line is this project

/** Turns npm repository fields ("github:a/b", "a/b", "git+ssh://git@github.com/a/b.git") into https links. */
function repoUrl(r) {
  let u = String(r || "").trim();
  if (!u) return "";
  u = u.replace(/^git\+/, "").replace(/\.git$/, "").replace(/#.*$/, "");
  if (/^github:/.test(u)) return `https://github.com/${u.slice(7)}`;
  if (/^[\w.-]+\/[\w.-]+$/.test(u)) return `https://github.com/${u}`;
  u = u.replace(/^ssh:\/\/git@/, "https://").replace(/^git@([^:]+):/, "https://$1/").replace(/^git:\/\//, "https://");
  return /^https?:\/\//.test(u) ? u : "";
}

const seen = new Map();
for (const line of lines) {
  const [dir, id] = line.split(":");
  if (!dir || !id || seen.has(id)) continue;
  let pkg;
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  } catch {
    continue;
  }
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(" OR ") : "UNKNOWN");
  const files = fs.readdirSync(dir).filter((f) => LICENSE_FILES.test(f));
  const text = files.map((f) => fs.readFileSync(path.join(dir, f), "utf8").trim()).join("\n\n");
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url ?? "";
  seen.set(id, { name: pkg.name, version: pkg.version, license, text, repo: repoUrl(repo) });
}

const pkgs = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const counts = pkgs.reduce((m, p) => m.set(p.license, (m.get(p.license) ?? 0) + 1), new Map());

let md = `# Third-party licenses

Foundry is built on open-source software. This file lists every package that ships with the app (production dependencies and everything they depend on), with its license and the license text the package includes.

Generated by \`npm run licenses\` on ${new Date().toISOString().slice(0, 10)}. Regenerate it after adding or updating packages.

## Summary

${pkgs.length} packages. Licenses: ${[...counts.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ")}.

| Package | Version | License |
| --- | --- | --- |
${pkgs.map((p) => `| ${p.repo ? `[${p.name}](${p.repo})` : p.name} | ${p.version} | ${p.license} |`).join("\n")}

## Fonts

The fonts are downloaded from Google Fonts at build time and served with the app.

| Font | Designer | License |
| --- | --- | --- |
| Instrument Serif | Instrument | SIL Open Font License 1.1 |
| Geist, Geist Mono | Vercel | SIL Open Font License 1.1 |

The SIL Open Font License 1.1 is at https://openfontlicense.org. It allows the fonts to be used, bundled and redistributed with software, as long as they aren't sold on their own.

## Notes

- Next.js bundles some smaller libraries inside its own package. Their license files are in \`node_modules/next/dist/compiled/\`.
- Development-only tools such as TypeScript aren't shipped with the app, so they aren't listed here.
- \`@img/sharp-libvips-*\` (LGPL-3.0-or-later) is an optional image library that Next.js installs for its image optimizer. Foundry doesn't use Next.js image optimization. The library is used unmodified and dynamically linked, which the LGPL allows. Its source is at https://github.com/lovell/sharp-libvips.
- For packages that don't include a license file, the full text of the declared license is on the linked SPDX page.

## License texts
`;

// Group identical texts so a license shared by many packages appears once.
const byText = new Map();
for (const p of pkgs) {
  const key = p.text || `No license file is included in this package. Declared license: ${p.license}\nFull text: https://spdx.org/licenses/${p.license}.html`;
  if (!byText.has(key)) byText.set(key, []);
  byText.get(key).push(`${p.name}@${p.version}`);
}
for (const [text, names] of byText) {
  md += `\n### ${names.join(", ")}\n\n\`\`\`\n${text.replace(/```/g, "'''")}\n\`\`\`\n`;
}

fs.writeFileSync(path.join(root, "THIRD_PARTY_LICENSES.md"), md);
console.log(`Wrote THIRD_PARTY_LICENSES.md with ${pkgs.length} packages (${byText.size} distinct license texts).`);
